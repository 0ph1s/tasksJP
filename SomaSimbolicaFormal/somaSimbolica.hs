-- 2. Auxiliar recursivo
sa :: String -> String -> Char -> String
sa [] [] '0' = []
sa [] [] '1' = ['1']
sa (x:xs) [] v = let (r, nv) = sd x '0' v in r : sa xs [] nv
sa [] (y:ys) v = let (r, nv) = sd '0' y v in r : sa [] ys nv
sa (x:xs) (y:ys) v = let (r, nv) = sd x y v in r : sa xs ys nv

-- 3. Soma de 2 entradas
s :: String -> String -> String
s a b = reverse (sa (reverse a) (reverse b) '0')

-- 4. Soma de lista de entradas
sl :: [String] -> String
sl [] = "0"
sl xs = foldl1 s xs